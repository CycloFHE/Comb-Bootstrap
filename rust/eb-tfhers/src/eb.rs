//! The error bootstrap (Sections 4 and 7 of the paper; case (B): p = 2N, B = 1) on TFHE-rs 1.8.1.
//!   refresh(ct): stair key switch N -> n, rounding at R = p̂·2N with recentering and selection, multi-bit blind
//!   rotation of TFHE-rs on the exponents of the coordinate-wise rounding (trait MultiBitModulusSwitchedLweCiphertext),
//!   test polynomial E ↦ E/R, sample extraction, subtraction from the noise-free encryption (ā, b̄ + c̄)/R of μ + E/R.
