/// f_c += w ⊙ Σ_{s,r} d_{r,s} ⊙ K[s][r][c] (c = 0, 1): the products of one pattern, its monomial applied, in one pass
/// (d: 2ℓ Fourier rows, index r ℓ + s; K: GGSW of TFHE-rs, [level s][input row r][output poly c][N/2]).
struct PatProd<'a> { f0: &'a mut [tfhe_fft::c64], f1: &'a mut [tfhe_fft::c64], w: &'a [tfhe_fft::c64], d: &'a [tfhe_fft::c64],
                     k: &'a [tfhe_fft::c64], l: usize, h: usize }
impl pulp::WithSimd for PatProd<'_> {
    type Output = ();
    #[inline(always)]
    fn with_simd<S: pulp::Simd>(self, simd: S) {
        let (h, l) = (self.h, self.l);
        let rows: Vec<(&[S::c64s], &[S::c64s], &[S::c64s])> = (0..l).flat_map(|s| (0..2).map(move |r| (s, r))).map(|(s, r)| {
            let d = S::as_simd_c64s(&self.d[(r * l + s) * h..(r * l + s + 1) * h]).0;
            let k0 = S::as_simd_c64s(&self.k[((s * 2 + r) * 2) * h..((s * 2 + r) * 2 + 1) * h]).0;
            let k1 = S::as_simd_c64s(&self.k[((s * 2 + r) * 2 + 1) * h..((s * 2 + r) * 2 + 2) * h]).0;
            (d, k0, k1)
        }).collect();
        let (f0, t0) = S::as_mut_simd_c64s(self.f0); let (f1, _) = S::as_mut_simd_c64s(self.f1);
        let w = S::as_simd_c64s(self.w).0;
        assert!(t0.is_empty());
        let zero = simd.splat_c64s(tfhe_fft::c64 { re: 0.0, im: 0.0 });
        for i in 0..f0.len() {
            let (mut a, mut b) = (zero, zero);
            for (d, k0, k1) in rows.iter() { a = simd.mul_add_c64s(k0[i], d[i], a); b = simd.mul_add_c64s(k1[i], d[i], b); }
            f0[i] = simd.mul_add_c64s(w[i], a, f0[i]); f1[i] = simd.mul_add_c64s(w[i], b, f1[i]);
        }
    }
}

/// Kernel of the products of Own2::rotate (A/B tests, bin rot_ab): 0 = PatProd (one pattern at a time, fused),
/// 1 = row by row (Mac2, as the external product of TFHE-rs) then the monomial (default: the fastest on the Apple M3
/// Max, results/rust/rot_ab_mac3.txt), 2 = PatProd3 (the three patterns together).
pub static OWN_KERNEL: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(1);

/// f_c += w ⊙ t_c (c = 0, 1).
struct MulAcc2<'a> { f0: &'a mut [tfhe_fft::c64], f1: &'a mut [tfhe_fft::c64], w: &'a [tfhe_fft::c64], t0: &'a [tfhe_fft::c64], t1: &'a [tfhe_fft::c64] }
impl pulp::WithSimd for MulAcc2<'_> {
    type Output = ();
    #[inline(always)]
    fn with_simd<S: pulp::Simd>(self, simd: S) {
        let (f0, _) = S::as_mut_simd_c64s(self.f0); let (f1, _) = S::as_mut_simd_c64s(self.f1);
        let (w, _) = S::as_simd_c64s(self.w); let (t0, _) = S::as_simd_c64s(self.t0); let (t1, _) = S::as_simd_c64s(self.t1);
        for ((((a, b), w), x), y) in f0.iter_mut().zip(f1.iter_mut()).zip(w).zip(t0).zip(t1) {
            *a = simd.mul_add_c64s(*w, *x, *a); *b = simd.mul_add_c64s(*w, *y, *b);
        }
    }
}

/// f_c += Σ_P w_P ⊙ Σ_{s,r} d_{r,s} ⊙ K_P[s][r][c], the three patterns at once: for each Fourier value, the six sums
/// stay in registers and each digit is loaded once (raw pointers: no bounds checks in the inner loop).
struct PatProd3<'a> { f0: &'a mut [tfhe_fft::c64], f1: &'a mut [tfhe_fft::c64], w: &'a [tfhe_fft::c64], d: &'a [tfhe_fft::c64],
                      k: [&'a [tfhe_fft::c64]; 3], l: usize, h: usize }
impl pulp::WithSimd for PatProd3<'_> {
    type Output = ();
    #[inline(always)]
    fn with_simd<S: pulp::Simd>(self, simd: S) {
        let (h, l) = (self.h, self.l);
        let lanes = std::mem::size_of::<S::c64s>() / std::mem::size_of::<tfhe_fft::c64>();
        assert!(h % lanes == 0);
        let nv = h / lanes;
        let mut dp: Vec<*const S::c64s> = Vec::with_capacity(2 * l);
        let mut kp: Vec<[*const S::c64s; 6]> = Vec::with_capacity(2 * l);
        for s in 0..l { for r in 0..2 {
            dp.push(S::as_simd_c64s(&self.d[(r * l + s) * h..(r * l + s + 1) * h]).0.as_ptr());
            let k = |p: usize, c: usize| S::as_simd_c64s(&self.k[p][((s * 2 + r) * 2 + c) * h..((s * 2 + r) * 2 + c + 1) * h]).0.as_ptr();
            kp.push([k(0, 0), k(0, 1), k(1, 0), k(1, 1), k(2, 0), k(2, 1)]);
        } }
        let (f0, _) = S::as_mut_simd_c64s(self.f0); let (f1, _) = S::as_mut_simd_c64s(self.f1);
        let w = S::as_simd_c64s(self.w).0;
        let zero = simd.splat_c64s(tfhe_fft::c64 { re: 0.0, im: 0.0 });
        for i in 0..nv {
            let mut a = [zero; 6];
            for (d, k) in dp.iter().zip(kp.iter()) {
                unsafe {
                    let x = *d.add(i);
                    a[0] = simd.mul_add_c64s(*k[0].add(i), x, a[0]); a[1] = simd.mul_add_c64s(*k[1].add(i), x, a[1]);
                    a[2] = simd.mul_add_c64s(*k[2].add(i), x, a[2]); a[3] = simd.mul_add_c64s(*k[3].add(i), x, a[3]);
                    a[4] = simd.mul_add_c64s(*k[4].add(i), x, a[4]); a[5] = simd.mul_add_c64s(*k[5].add(i), x, a[5]);
                }
            }
            let (w0, w1, w2) = (w[i], w[nv + i], w[2 * nv + i]);
            f0[i] = simd.mul_add_c64s(w2, a[4], simd.mul_add_c64s(w1, a[2], simd.mul_add_c64s(w0, a[0], f0[i])));
            f1[i] = simd.mul_add_c64s(w2, a[5], simd.mul_add_c64s(w1, a[3], simd.mul_add_c64s(w0, a[1], f1[i])));
        }
    }
}

pub struct Times { pub ks: f64, pub rounding: f64, pub rotation: f64, pub rest: f64 }

pub fn cm() -> CiphertextModulus<u64> { CiphertextModulus::new_native() }

impl EbKeys {
    /// Keys for the configuration cfg with the mask grouped by m in the rotation (m = 1: classic rotation of TFHE-rs;
    /// m = 2: our multi-bit rotation on the FFT of TFHE-rs (Own2), or that of TFHE-rs with the environment variable
    /// TFHEMB=1; m ≥ 3: multi-bit rotation of TFHE-rs); an empty chain gives no key switch (refresh_small only).
    pub fn new(cfg: &Config, m: usize, seed: u64) -> (Self, EncryptionRandomGenerator<DefaultRandomGenerator>) {
        let mut boxed = new_seeder(); let seeder = boxed.as_mut();
        let mut sgen = SecretRandomGenerator::<DefaultRandomGenerator>::new(Seed(seed as u128));
        let mut egen = EncryptionRandomGenerator::<DefaultRandomGenerator>::new(seeder.seed(), seeder);
        let glwe_sk = GlweSecretKey::generate_new_binary(GlweDimension(1), PolynomialSize(N), &mut sgen);
        let big_sk = glwe_sk.clone().into_lwe_secret_key();
        let small_sk = LweSecretKey::from_container(big_sk.as_ref()[..cfg.n].to_vec());   // s = first n coordinates of s'
        let glwe_noise = Gaussian::from_dispersion_parameter(StandardDev(2f64.powf(LOG2_SIGMA_N)), 0.0);
        let bsk = if m == 1 {
            let std = par_allocate_and_generate_new_lwe_bootstrap_key(&small_sk, &glwe_sk, DecompositionBaseLog(cfg.b),
                DecompositionLevelCount(cfg.l), glwe_noise, cm(), &mut egen);
            let mut f = FourierLweBootstrapKey::new(std.input_lwe_dimension(), std.glwe_size(), std.polynomial_size(),
                std.decomposition_base_log(), std.decomposition_level_count());
            par_convert_standard_lwe_bootstrap_key_to_fourier(&std, &mut f);
            Bsk::Classic(f)
        } else if m == 2 && std::env::var("TFHEMB").is_err() {
            Bsk::Own2(Own2::new(&small_sk, &glwe_sk, cfg.b, cfg.l, glwe_noise, &mut egen))
        } else {
            assert!(cfg.n % m == 0, "n must be a multiple of m");
            let mut std = LweMultiBitBootstrapKey::new(0u64, GlweDimension(1).to_glwe_size(), PolynomialSize(N),
                DecompositionBaseLog(cfg.b), DecompositionLevelCount(cfg.l), LweDimension(cfg.n), LweBskGroupingFactor(m), cm());
            par_generate_lwe_multi_bit_bootstrap_key(&small_sk, &glwe_sk, &mut std, glwe_noise, &mut egen);
            let mut f = FourierLweMultiBitBootstrapKey::new(std.input_lwe_dimension(), std.glwe_size(), std.polynomial_size(),
                std.decomposition_base_log(), std.decomposition_level_count(), std.grouping_factor());
            par_convert_standard_lwe_multi_bit_bootstrap_key_to_fourier(&std, &mut f);
            Bsk::MultiBit(f)
        };
        let mut rng = StdRng::seed_from_u64(seed ^ 0x5eed);
        let stair = if cfg.chain.is_empty() { None } else { Some(StairKey::new(big_sk.as_ref(), N, cfg.chain, &mut rng)) };
        // public encryptions of zero under s, noise σ_128(n)
        let pool_noise = Gaussian::from_dispersion_parameter(StandardDev(2f64.powf(log2_sigma128(cfg.n))), 0.0);
        let pool = (0..128).map(|_| {
            let z: LweCiphertextOwned<u64> = allocate_and_encrypt_new_lwe_ciphertext(&small_sk, Plaintext(0), pool_noise, cm(), &mut egen);
            (z.get_mask().as_ref().to_vec(), *z.get_body().data)
        }).collect();
        let log_r = 2 * cfg.k + (2 * N).trailing_zeros();
        // test polynomial: E ↦ E/R for |E| < N/2 (negacyclic: v_i = i/R, then (N - i)/R)
        let scale = 1u64 << (64 - log_r);
        let lut = PlaintextList::from_container((0..N).map(|i| (if i < N / 2 { i } else { N - i }) as u64 * scale).collect::<Vec<u64>>());
        let vstar = cfg.vterm * ((2 * N) as f64).powi(2) / 16.0;
        (EbKeys { k: cfg.k, n: cfg.n, m, log_r, vstar, big_sk, small_sk, bsk, stair, pool, lut }, egen)
    }

    /// Refresh of an LWE ciphertext of dimension n under s (no key switch).
    pub fn refresh_small<RG: Rng>(&self, a: &[u64], b: u64, rng: &mut RG, t: Option<&mut Times>) -> LweCiphertextOwned<u64> {
        let t0 = Instant::now();
        let r = round_select(a, b, self.log_r, &self.pool, self.vstar, rng);
        let t1 = Instant::now();
        let mut acc = allocate_and_trivially_encrypt_new_glwe_ciphertext(GlweDimension(1).to_glwe_size(), &self.lut, cm());
        let two_n = 2 * N as u64;
        match &self.bsk {
            Bsk::Classic(f) => blind_rotate_assign(&Msed1 { r: &r, two_n }, &mut acc, f),
            Bsk::MultiBit(f) => multi_bit_blind_rotate_assign(&Msed { r: &r, two_n, m: self.m }, &mut acc, f, ThreadCount(1), true),
            Bsk::Own2(o) => self.rotate_own2(o, &r, &mut acc),
        }
        let t2 = Instant::now();
        let mut out = LweCiphertext::new(0u64, LweSize(N + 1), cm());
        extract_lwe_sample_from_glwe_ciphertext(&acc, &mut out, MonomialDegree(0));
        let shift = 64 - self.log_r;
        let mut fin = LweCiphertext::new(0u64, LweSize(N + 1), cm());
        {
            let (mut fm, fb) = fin.get_mut_mask_and_body();
            for (u, &x) in r.abar.iter().enumerate() { fm.as_mut()[u] = x << shift; }
            *fb.data = r.bbar << shift;
        }
        lwe_ciphertext_sub_assign(&mut fin, &out);
        if let Some(t) = t {
            t.rounding += (t1 - t0).as_secs_f64() * 1e3; t.rotation += (t2 - t1).as_secs_f64() * 1e3;
            t.rest += t2.elapsed().as_secs_f64() * 1e3;
        }
        fin
    }

    /// Blind rotation of the classic form (m = 1) on t threads, with the keys of TFHE-rs and the same steps as its
    /// blind_rotate_assign (acc = X^-b v; for a_i ≠ 0: acc += ExtProd(GGSW(s_i), X^a_i acc - acc)), the external
    /// products being split between the threads (crate::mt::ext_prod_mt).
    pub fn rotate_mt(&self, r: &Rounded, threads: usize) -> GlweCiphertextOwned<u64> {
        use crate::mt::{ext_prod_mt, prof_on, ExtProdBufs, Lap, Sh, SpinBarrier};
        use tfhe_fft::c64;
        let f = match &self.bsk { Bsk::Classic(f) => f, _ => panic!("rotate_mt: m = 1 only") };
        let t = threads.max(1); let two_n = 2 * N;
        let (b, l) = (f.decomposition_base_log().0 as u32, f.decomposition_level_count().0);
        let mut c = vec![0u64; 2 * N];
        let dg = (two_n - (r.bbar as usize % two_n)) % two_n;
        let lut = self.lut.as_ref();
        for j in 0..N { let s = (j + two_n - dg) % two_n; c[N + j] = if s < N { lut[s] } else { lut[s - N].wrapping_neg() }; }
        let z = c64 { re: 0.0, im: 0.0 };
        let (mut ed, mut fd, mut fo) = (vec![0u64; 2 * l * N], vec![z; 2 * l * N / 2], vec![z; N]);
        let bufs = ExtProdBufs { ed: Sh::of(&mut ed), fd: Sh::of(&mut fd), fo: Sh::of(&mut fo) };
        let ggsw: Vec<&[c64]> = f.as_view().into_ggsw_iter().map(|g| g.data()).collect();
        let exps: Vec<usize> = r.abar.iter().map(|&a| (a % two_n as u64) as usize).collect();
        let pc = Sh::of(&mut c);
        let bar = SpinBarrier::new(t);
        let fft = Fft::new(PolynomialSize(N));
        let worker = |w: usize| {
            let fv = fft.as_view();
            let mut buf = ComputationBuffers::new();
            buf.resize(fv.forward_scratch().unaligned_bytes_required().max(fv.backward_scratch().unaligned_bytes_required()));
            let mut lap = Lap::new(w == 0 && prof_on());
            for (u, &e) in exps.iter().enumerate() {
                if e == 0 { continue; }
                ext_prod_mt(w, t, N, pc, pc, ggsw[u], b, l, &bufs, fv, &mut buf, &bar, &mut lap, Some(e));
            }
        };
        std::thread::scope(|sc| {
            for w in 1..t { let wk = &worker; sc.spawn(move || wk(w)); }
            worker(0);
        });
        GlweCiphertext::from_container(c, PolynomialSize(N), cm())
    }

    /// Whole refresh with the rotation on t threads (key switch and rounding on one thread: a fraction of a ms).
    pub fn refresh_mt<RG: Rng>(&self, ct: &LweCiphertextOwned<u64>, rng: &mut RG, rbit: &mut u64, threads: usize) -> LweCiphertextOwned<u64> {
        let (a, b) = self.stair.as_ref().expect("no key switch").switch(ct.get_mask().as_ref(), *ct.get_body().data, rbit);
        let r = round_select(&a, b, self.log_r, &self.pool, self.vstar, rng);
        let acc = self.rotate_mt(&r, threads);
        self.finish(&r, &acc)
    }

    /// Extraction of the constant coefficient and subtraction from the noise-free encryption of μ + E/R.
    pub fn finish(&self, r: &Rounded, acc: &GlweCiphertextOwned<u64>) -> LweCiphertextOwned<u64> {
        let mut out = LweCiphertext::new(0u64, LweSize(N + 1), cm());
        extract_lwe_sample_from_glwe_ciphertext(acc, &mut out, MonomialDegree(0));
        let shift = 64 - self.log_r;
        let mut fin = LweCiphertext::new(0u64, LweSize(N + 1), cm());
        {
            let (mut fm, fb) = fin.get_mut_mask_and_body();
            for (u, &x) in r.abar.iter().enumerate() { fm.as_mut()[u] = x << shift; }
            *fb.data = r.bbar << shift;
        }
        lwe_ciphertext_sub_assign(&mut fin, &out);
        fin
    }

    /// Our multi-bit rotation (m = 2) of the accumulator X^-b̄ v (already the trivial encryption of v): acc <- X^-b̄ acc,
    /// then the pairs of exponents (Own2::rotate).
    fn rotate_own2(&self, o: &Own2, r: &Rounded, acc: &mut GlweCiphertextOwned<u64>) {
        let two_n = 2 * N;
        let dg = (two_n - (r.bbar as usize % two_n)) % two_n;
        let c = acc.as_mut();
        let body: Vec<u64> = c[N..].to_vec();
        for j in 0..N { let s = (j + two_n - dg) % two_n; c[N + j] = if s < N { body[s] } else { body[s - N].wrapping_neg() }; }
        let exps: Vec<usize> = r.abar.iter().map(|&a| (a % two_n as u64) as usize).collect();
        o.rotate(&exps, c);
    }

    /// Single-thread rotation of TFHE-rs on a rounded ciphertext (for comparison with rotate_mt).
    pub fn rotate_st(&self, r: &Rounded) -> GlweCiphertextOwned<u64> {
        let mut acc = allocate_and_trivially_encrypt_new_glwe_ciphertext(GlweDimension(1).to_glwe_size(), &self.lut, cm());
        let two_n = 2 * N as u64;
        match &self.bsk {
            Bsk::Classic(f) => blind_rotate_assign(&Msed1 { r, two_n }, &mut acc, f),
            Bsk::MultiBit(f) => multi_bit_blind_rotate_assign(&Msed { r, two_n, m: self.m }, &mut acc, f, ThreadCount(1), true),
            Bsk::Own2(o) => self.rotate_own2(o, r, &mut acc),
        }
        acc
    }

    /// RNS: whole refresh of an LWE ciphertext of dimension N under s' encrypting μ/p̂ with any integer p̂ (`phat`): the
    /// stair key switch, the rounding with selection at the resolution R = 2N p̂ (multiplication by p̂ and rounding modulo
    /// 2N), the rotation of the test polynomial v_i = round(2^64 min(i, N - i)/R), the extraction and the subtraction from
    /// the rounded ciphertext (its torus representation rounded to 2^-64: an error below n 2^-65 on the phase). For
    /// p̂ = 4^k, the same as refresh up to these roundings.
    pub fn refresh_rns<RG: Rng>(&self, ct: &LweCiphertextOwned<u64>, phat: u64, rng: &mut RG, rbit: &mut u64) -> LweCiphertextOwned<u64> {
        let (a, b) = self.stair.as_ref().expect("no key switch").switch(ct.get_mask().as_ref(), *ct.get_body().data, rbit);
        let rr = 2 * N as u64 * phat;
        let r = round_select_r(&a, b, rr, &self.pool, self.vstar, rng);
        let lift = |x: u64| -> u64 { ((((x as u128) << 64) + rr as u128 / 2) / rr as u128) as u64 };
        let lut = PlaintextList::from_container((0..N).map(|i| lift((if i < N / 2 { i } else { N - i }) as u64)).collect::<Vec<u64>>());
        let mut acc = allocate_and_trivially_encrypt_new_glwe_ciphertext(GlweDimension(1).to_glwe_size(), &lut, cm());
        let two_n = 2 * N as u64;
        match &self.bsk {
            Bsk::Classic(f) => blind_rotate_assign(&Msed1 { r: &r, two_n }, &mut acc, f),
            Bsk::MultiBit(f) => multi_bit_blind_rotate_assign(&Msed { r: &r, two_n, m: self.m }, &mut acc, f, ThreadCount(1), true),
            Bsk::Own2(o) => self.rotate_own2(o, &r, &mut acc),
        }
        let mut out = LweCiphertext::new(0u64, LweSize(N + 1), cm());
        extract_lwe_sample_from_glwe_ciphertext(&acc, &mut out, MonomialDegree(0));
        let mut fin = LweCiphertext::new(0u64, LweSize(N + 1), cm());
        {
            let (mut fm, fb) = fin.get_mut_mask_and_body();
            for (u, &x) in r.abar.iter().enumerate() { fm.as_mut()[u] = lift(x); }
            *fb.data = lift(r.bbar);
        }
        lwe_ciphertext_sub_assign(&mut fin, &out);
        fin
    }

    /// Whole refresh of an LWE ciphertext of dimension N under s'.
    pub fn refresh<RG: Rng>(&self, ct: &LweCiphertextOwned<u64>, rng: &mut RG, rbit: &mut u64, t: Option<&mut Times>) -> LweCiphertextOwned<u64> {
        let t0 = Instant::now();
        let (a, b) = self.stair.as_ref().expect("no key switch").switch(ct.get_mask().as_ref(), *ct.get_body().data, rbit);
        let ks = t0.elapsed().as_secs_f64() * 1e3;
        match t { Some(t) => { t.ks += ks; self.refresh_small(&a, b, rng, Some(t)) } None => self.refresh_small(&a, b, rng, None) }
    }
}

/// Signed torus value of x in (-1/2, 1/2].
pub fn tor(x: u64) -> f64 { (x as i64) as f64 * 2f64.powi(-64) }
