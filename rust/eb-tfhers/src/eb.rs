/// The rounded ciphertext seen by the multi-bit rotation of TFHE-rs (m ≥ 2): body and exponents of the patterns,
/// modulo 2N, the exponent of a pattern being the sum of the rounded coordinates it selects (coordinate-wise rounding).
struct Msed<'a> { r: &'a Rounded, two_n: u64, m: usize }

impl MultiBitModulusSwitchedLweCiphertext for Msed<'_> {
    fn lwe_dimension(&self) -> LweDimension { LweDimension(self.r.abar.len()) }
    fn grouping_factor(&self) -> LweBskGroupingFactor { LweBskGroupingFactor(self.m) }
    fn switched_modulus_input_lwe_body(&self) -> usize { (self.r.bbar % self.two_n) as usize }
    fn switched_modulus_input_mask_per_group(&self, index: usize) -> impl Iterator<Item = usize> + '_ {
        let m = self.m;
        let a = &self.r.abar[index * m..(index + 1) * m];
        // pattern order of tfhe-rs (selection_bit)
        (1..(1usize << m)).map(move |psi| {
            let mut d = 0u64;
            for (i, &ai) in a.iter().enumerate() { if (psi >> (m - (i + 1))) & 1 == 1 { d = d.wrapping_add(ai); } }
            (d % self.two_n) as usize
        })
    }
}

/// The same for the classic rotation of TFHE-rs (m = 1).
struct Msed1<'a> { r: &'a Rounded, two_n: u64 }

impl ModulusSwitchedLweCiphertext<usize> for Msed1<'_> {
    fn log_modulus(&self) -> CiphertextModulusLog { CiphertextModulusLog(self.two_n.trailing_zeros() as usize) }
    fn lwe_dimension(&self) -> LweDimension { LweDimension(self.r.abar.len()) }
    fn body(&self) -> usize { (self.r.bbar % self.two_n) as usize }
    fn mask(&self) -> impl ExactSizeIterator<Item = usize> + '_ { self.r.abar.iter().map(move |&a| (a % self.two_n) as usize) }
}

pub enum Bsk { Classic(FourierLweBootstrapKeyOwned), MultiBit(FourierLweMultiBitBootstrapKeyOwned), Own2(Own2) }

/// Our multi-bit rotation for m = 2 on the FFT of TFHE-rs (as the multi-bit form of julia/src/grouped.jl): for each pair
/// (s_2g, s_2g+1) of key bits with rounded exponents (e0, e1), the three patterns P = 10, 01, 11 have the keys
/// GGSW(ind_P), ind_10 = s0 (1 - s1), ind_01 = (1 - s0) s1, ind_11 = s0 s1, and the exponents e0, e1, e0 + e1; then
///     acc <- acc + Σ_P (X^{e_P} - 1) ExtProd(GGSW(ind_P), acc) = X^{e0 s0 + e1 s1} acc:
/// one decomposition of acc and 2ℓ forward FFTs per pair, the products by the three keys in the Fourier domain, the
/// monomials X^{e_P} - 1 applied there (pointwise, on the roots at which TFHE-rs evaluates), and 2 backward FFTs.
/// The keys of the patterns are generated by TFHE-rs as the bootstrapping key of the vector of indicators.
pub struct Own2 { pub f: FourierLweBootstrapKeyOwned, pub theta: Vec<usize>, pub roots: Vec<tfhe_fft::c64>, pub fft: Fft, prof: bool }

impl Own2 {
    fn new<G: ParallelByteRandomGenerator>(small_sk: &LweSecretKeyOwned<u64>, glwe_sk: &GlweSecretKeyOwned<u64>, b: usize, l: usize,
                                           noise: Gaussian<f64>, egen: &mut EncryptionRandomGenerator<G>) -> Self {
        let s = small_sk.as_ref(); assert!(s.len() % 2 == 0, "n must be even for m = 2");
        let ind: Vec<u64> = s.chunks(2).flat_map(|p| [p[0] & !p[1] & 1, !p[0] & p[1] & 1, p[0] & p[1]]).collect();
        let ind_sk = LweSecretKey::from_container(ind);
        let std = par_allocate_and_generate_new_lwe_bootstrap_key(&ind_sk, glwe_sk, DecompositionBaseLog(b),
            DecompositionLevelCount(l), noise, cm(), egen);
        let mut f = FourierLweBootstrapKey::new(std.input_lwe_dimension(), std.glwe_size(), std.polynomial_size(),
            std.decomposition_base_log(), std.decomposition_level_count());
        par_convert_standard_lwe_bootstrap_key_to_fourier(&std, &mut f);
        let fft = Fft::new(PolynomialSize(N)); let two_n = 2 * N;
        let roots = (0..two_n).map(|e| { let t = std::f64::consts::PI * e as f64 / N as f64; tfhe_fft::c64 { re: t.cos(), im: t.sin() } }).collect();
        // root exponents of the Fourier values of TFHE-rs: transform of X
        let mut buf = ComputationBuffers::new();
        buf.resize(fft.as_view().forward_scratch().unaligned_bytes_required());
        let mut xpoly = vec![0u64; N]; xpoly[1] = 1;
        let mut fx = tfhe::core_crypto::fft_impl::fft64::math::polynomial::FourierPolynomial::new(PolynomialSize(N));
        fft.as_view().forward_as_integer(fx.as_mut_view(), Polynomial::from_container(xpoly.as_slice()), buf.stack());
        let theta: Vec<usize> = fx.data.iter().map(|z| {
            let c = (z.im.atan2(z.re) * N as f64 / std::f64::consts::PI).round() as i64; c.rem_euclid(two_n as i64) as usize
        }).collect();
        assert!(theta.iter().all(|&c| c % 2 == 1), "unexpected Fourier layout");
        Own2 { f, theta, roots, fft, prof: std::env::var("OWNPROF").is_ok() }
    }

    /// acc <- X^{Σ_u e_u s_u} acc (exponents modulo 2N, n even).
    pub fn rotate(&self, exps: &[usize], acc: &mut [u64]) {
        use tfhe::core_crypto::fft_impl::fft64::math::polynomial::FourierPolynomial;
        use tfhe_fft::c64;
        let (two_n, h) = (2 * N, N / 2);
        let (b, l) = (self.f.decomposition_base_log().0 as u32, self.f.decomposition_level_count().0);
        let fv = self.fft.as_view();
        let mut buf = ComputationBuffers::new();
        buf.resize(fv.forward_scratch().unaligned_bytes_required().max(fv.backward_scratch().unaligned_bytes_required()));
        let z = c64 { re: 0.0, im: 0.0 };
        let (mut ed, mut fd, mut st) = (vec![0u64; 2 * l * N], vec![z; 2 * l * h], vec![0u64; N]);
        let (mut f0, mut f1, mut w) = (vec![z; h], vec![z; h], vec![z; 3 * h]);
        let (mut t0, mut t1) = (vec![z; h], vec![z; h]);
        let kern = OWN_KERNEL.load(std::sync::atomic::Ordering::Relaxed);
        let arch = pulp::Arch::new();
        let mut lp = OLap::new(self.prof);
        let ggsw: Vec<&[c64]> = self.f.as_view().into_ggsw_iter().map(|g| g.data()).collect();
        let rep = b * l as u32; let nr = 64 - rep; let mask = u64::MAX >> (64 - rep); let mb = (1u64 << b) - 1;
        for g in 0..exps.len() / 2 {
            let (e0, e1) = (exps[2 * g], exps[2 * g + 1]);
            if e0 == 0 && e1 == 0 { continue; }
            let es = [e0, e1, (e0 + e1) % two_n];
            lp.lap(5);
            // signed decomposition of TFHE-rs of acc, level by level (least significant first)
            for r in 0..2 {
                let cc = &acc[r * N..(r + 1) * N];
                for i in 0..N {
                    let x = cc[i];
                    let mut res = x >> (nr - 1); let rb = res & 1; res = ((res + 1) >> 1) & mask;
                    let nb = ((res.wrapping_sub(1) | (rb << (rep - 1))) & res) >> (rep - 1);
                    st[i] = res.wrapping_sub(nb << rep);
                }
                for s in 0..l {
                    let out = &mut ed[(r * l + s) * N..(r * l + s + 1) * N];
                    for i in 0..N {
                        let v = st[i]; let rr = v & mb; let v = ((v as i64) >> b) as u64;
                        let carry = ((rr.wrapping_sub(1) | v) & rr) >> (b - 1);
                        st[i] = v.wrapping_add(carry); out[i] = rr.wrapping_sub(carry << b);
                    }
                }
            }
            lp.lap(0);
            for k in 0..2 * l {
                fv.forward_as_integer(FourierPolynomial { data: &mut fd[k * h..(k + 1) * h] },
                                      Polynomial::from_container(&ed[k * N..(k + 1) * N]), buf.stack());
            }
            lp.lap(1);
            // monomials X^{e_P} - 1 at the roots ψ^{θ_j}: w0, w1 by table, w2 = (w0 + 1)(w1 + 1) - 1
            for j in 0..h {
                let r0 = self.roots[(self.theta[j] * e0) & (two_n - 1)]; let r1 = self.roots[(self.theta[j] * e1) & (two_n - 1)];
                w[j] = c64 { re: r0.re - 1.0, im: r0.im }; w[h + j] = c64 { re: r1.re - 1.0, im: r1.im };
                w[2 * h + j] = c64 { re: r0.re * r1.re - r0.im * r1.im - 1.0, im: r0.re * r1.im + r0.im * r1.re };
            }
            lp.lap(2);
            f0.fill(z); f1.fill(z);
            match kern {
                1 => {   // row by row, as the external product of TFHE-rs (Mac2), then the monomial
                    for (p, &e) in es.iter().enumerate() {
                        if e == 0 { continue; }
                        t0.fill(z); t1.fill(z);
                        let gk = ggsw[3 * g + p];
                        for s in 0..l { for r in 0..2 {
                            let dk = &fd[(r * l + s) * h..(r * l + s + 1) * h];
                            let g0 = &gk[((s * 2 + r) * 2) * h..((s * 2 + r) * 2 + 1) * h];
                            let g1 = &gk[((s * 2 + r) * 2 + 1) * h..((s * 2 + r) * 2 + 2) * h];
                            arch.dispatch(crate::mt::Mac2 { o0: &mut t0, o1: &mut t1, d: dk, g0, g1 });
                        } }
                        arch.dispatch(MulAcc2 { f0: &mut f0, f1: &mut f1, w: &w[p * h..(p + 1) * h], t0: &t0, t1: &t1 });
                    }
                }
                2 => {   // the three patterns together, accumulators in registers
                    arch.dispatch(PatProd3 { f0: &mut f0, f1: &mut f1, w: &w, d: &fd, k: [ggsw[3 * g], ggsw[3 * g + 1], ggsw[3 * g + 2]], l, h });
                }
                _ => {
                    for (p, &e) in es.iter().enumerate() {
                        if e == 0 { continue; }
                        arch.dispatch(PatProd { f0: &mut f0, f1: &mut f1, w: &w[p * h..(p + 1) * h], d: &fd, k: ggsw[3 * g + p], l, h });
                    }
                }
            }
            lp.lap(3);
            let (a0, a1) = acc.split_at_mut(N);
            fv.add_backward_as_torus(Polynomial::from_container(a0), FourierPolynomial { data: &f0[..] }, buf.stack());
            fv.add_backward_as_torus(Polynomial::from_container(a1), FourierPolynomial { data: &f1[..] }, buf.stack());
            lp.lap(4);
        }
    }
}
/// Profile of Own2::rotate (environment variable OWNPROF): ns spent in the decomposition, the forward FFTs, the
/// monomials, the products and the backward FFTs (OPROF[0..5]).
pub static OPROF: [std::sync::atomic::AtomicU64; 6] = [const { std::sync::atomic::AtomicU64::new(0) }; 6];
struct OLap { on: bool, t: Instant }
impl OLap {
    fn new(on: bool) -> Self { OLap { on, t: Instant::now() } }
    #[inline] fn lap(&mut self, i: usize) {
        if self.on { let t = Instant::now(); OPROF[i].fetch_add((t - self.t).as_nanos() as u64, std::sync::atomic::Ordering::Relaxed); self.t = t; }
    }
}

